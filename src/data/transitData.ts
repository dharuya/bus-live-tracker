// Complete Daily Route Timetables
export const generateDailyTripsForRoute = (route: BusRoute): RouteTrip[] => {
  const trips: RouteTrip[] = [];
  const startHour = parseInt(route.firstBus.split(':')[0], 10);
  const endHour = 22; // 10 PM
  let tripIndex = 1;

  for (let hour = startHour; hour <= endHour; hour++) {
    const minuteSlots = [0, route.frequencyMinutes];
    for (const min of minuteSlots) {
      if (min >= 60) continue;
      const formattedDeparture = `${hour.toString().padStart(2, '0')}:${min.toString().padStart(2, '0')}`;
      const departureDate = new Date();
      departureDate.setHours(hour, min, 0, 0);

      const stopIntervalMinutes = Math.round(route.avgDurationMinutes / (route.stops.length - 1 || 1));
      
      const stopsTimeline = route.stops.map((stopId, idx) => {
        const stop = BUS_STOPS.find(s => s.id === stopId);
        const arrivalDate = new Date(departureDate.getTime() + idx * stopIntervalMinutes * 60000);
        const departureDateStop = new Date(arrivalDate.getTime() + (idx === 0 || idx === route.stops.length - 1 ? 0 : 2) * 60000);
        
        const formatTime = (d: Date) => {
          let h = d.getHours();
          const m = d.getMinutes().toString().padStart(2, '0');
          const ampm = h >= 12 ? 'PM' : 'AM';
          h = h % 12;
          h = h ? h : 12;
          return `${h.toString().padStart(2, '0')}:${m} ${ampm}`;
        };

        const distanceFraction = (idx / (route.stops.length - 1 || 1)) * route.distanceKm;

        return {
          stopId,
          stopName: stop ? stop.name : stopId,
          scheduledArrivalTime: formatTime(arrivalDate),
          scheduledDepartureTime: formatTime(departureDateStop),
          platformOrBay: `Bay ${((idx % 4) + 1)}`,
          distanceFromStartKm: parseFloat(distanceFraction.toFixed(1)),
        };
      });

      const arrivalTime = stopsTimeline[stopsTimeline.length - 1].scheduledArrivalTime;

      trips.push({
        tripId: `${route.id}-trip-${tripIndex}`,
        tripNumber: tripIndex,
        departureTime: stopsTimeline[0].scheduledDepartureTime,
        arrivalTime,
        serviceType: route.serviceType,
        schedule: stopsTimeline,
      });

      tripIndex++;
    }
  }

  return trips;
};
